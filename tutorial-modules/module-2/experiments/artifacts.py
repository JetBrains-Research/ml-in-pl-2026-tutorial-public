"""Keep Gym's native evidence and the workshop console in one run directory."""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import traceback
from collections.abc import Callable, Iterator
from contextlib import contextmanager, redirect_stderr, redirect_stdout
from contextvars import ContextVar
from datetime import datetime, timezone
from functools import wraps
from pathlib import Path
from typing import Optional, TextIO

import click
from omegaconf import DictConfig, OmegaConf

from experiments.common import ROOT

_output: ContextVar[Optional[Path]] = ContextVar("run_output", default=None)


def current_output() -> Optional[Path]:
    return _output.get()


def new_output(module_root: Path, output: Optional[Path], suffix: str) -> Path:
    active = current_output()
    if active is not None and output is not None and output.resolve() == active:
        return active
    if output is None:
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%S.%fZ")
        output = ROOT / "results" / module_root.name / f"{stamp}-{suffix}"
    output = output.resolve()
    if output.exists():
        raise click.ClickException(f"Output directory already exists: {output}; choose a new directory")
    output.mkdir(parents=True, mode=0o700)
    return output


class ConsoleLog:
    def __init__(self, console: TextIO, log: TextIO) -> None:
        self.console = console
        self.log = log

    def write(self, text: str) -> int:
        self.console.write(text)
        self.log.write(text)
        self.flush()
        return len(text)

    def flush(self) -> None:
        self.console.flush()
        self.log.flush()

    def fileno(self) -> int:
        return self.console.fileno()

    def isatty(self) -> bool:
        return False


def snapshot_inputs(module_root: Path, output: Path) -> None:
    inputs = output / "inputs"
    shutil.copytree(module_root / "data", inputs)
    if module_root.name in ("module_2_direct_bash", "module_3_openenv_bash"):
        shutil.copyfile(ROOT / "data/calculator.json", inputs / "calculator.json")
    configuration = OmegaConf.load(module_root / "config.yaml")
    for _, entry in configuration.items_ex(resolve=False):
        if not OmegaConf.is_dict(entry):
            continue
        for category in ("responses_api_agents", "resources_servers"):
            if category in entry:
                for component in entry[category].values():
                    for dataset in component.get("datasets", []):
                        dataset.jsonl_fpath = str(inputs / Path(dataset.jsonl_fpath).name)
    save_configuration(configuration, output)


def save_configuration(configuration: DictConfig, output: Path) -> None:
    configuration.results_dir = str(output)
    configuration.uv_venv_dir = os.environ.get("POC_RUNTIME_DIR", str(ROOT / ".runtime"))
    configuration.nemo_gym_log_dir = str(output / "logs")
    configuration.model_call_capture_dir = str(output / "model-calls")
    OmegaConf.save(configuration, output / "config.yaml", resolve=False)


@contextmanager
def run_runtime() -> Iterator[None]:
    # Gym environments and Ray sockets are transient and need a local filesystem.
    with tempfile.TemporaryDirectory(prefix="ng-", dir="/tmp") as temporary:
        names = ("RAY_TMPDIR", "POC_RUNTIME_DIR")
        previous = {name: os.environ.get(name) for name in names}
        os.environ.update(RAY_TMPDIR=temporary, POC_RUNTIME_DIR=str(Path(temporary) / "components"))
        try:
            yield
        finally:
            for name, value in previous.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value


def write_trace(output: Path) -> None:
    trajectory = output / "trajectory.jsonl"
    if not trajectory.exists():
        return
    sections = ["# Model trace\n\nFormatted from `trajectory.jsonl`; no authored interpretation.\n"]
    for line in trajectory.read_text().splitlines():
        entry = json.loads(line)
        if "tool" in entry:
            sections.append(f"\n## Tool: {entry['tool']} ({'ERROR' if entry['is_error'] else 'OK'})\n")
        else:
            sections.append(f"\n## Model turn {entry['step']}\n")
        sections.append("\n```json\n" + json.dumps(entry, indent=2) + "\n```\n")
    (output / "trace.md").write_text("".join(sections))


def write_index(output: Path, record: dict) -> None:
    lines = [
        f"# {record['module']} — {record['mode']} run",
        "",
        "Generated by the runner from saved evidence; no authored interpretation.",
        "",
        f"Status: **{record['status']}**. Started: {record['started_at']}.",
        "",
        "Gym owns scored rollouts, aggregate metrics, failure records, prepared datasets,",
        "service logs, and model-call captures. Workshop files add console/progress output,",
        "sandbox identities, submitted sources, and environment-specific verification.",
        "",
    ]
    summary = output / "summary.json"
    if summary.exists():
        lines.extend(["## Result", "", "```json", summary.read_text().strip(), "```", ""])
    lines.extend(["## Files", ""])
    for path in sorted(output.rglob("*")):
        relative = path.relative_to(output)
        # Docker Desktop bind mounts may reject stat() on Ray's Unix sockets.
        # Runtime sockets are not saved evidence; keep their logs in the index.
        if ".venv" in relative.parts or (relative.parts[0] == "ray" and "sockets" in relative.parts):
            continue
        if path.is_file() and path.name != "README.md":
            name = relative.as_posix()
            lines.append(f"- [{name}]({name})")
    (output / "README.md").write_text("\n".join(lines) + "\n")


def record_run(module_root: Path) -> Callable:
    def decorate(callback: Callable) -> Callable:
        @wraps(callback)
        def run(*args, **kwargs):
            mode = "golden" if kwargs.get("golden") else "model"
            output = new_output(module_root, kwargs.get("output_dir"), mode)
            kwargs["output_dir"] = output
            token = _output.set(output)
            record = {
                "module": module_root.name,
                "mode": mode,
                "started_at": datetime.now(timezone.utc).isoformat(),
                "status": "running",
            }
            revision = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=False
            )
            record["git_commit"] = revision.stdout.strip() or None
            environment = ("POC_RUN_DIR", "POC_LOG_DIR", "POC_RUNTIME_DIR", "POC_WORKSHOP_EVENTS", "RAY_TMPDIR")
            previous = {name: os.environ.get(name) for name in environment}
            os.environ.update(
                POC_RUN_DIR=str(output),
                POC_LOG_DIR=str(output / "logs"),
                POC_WORKSHOP_EVENTS=str(output / "progress.jsonl"),
            )
            (output / "progress.jsonl").touch()
            (output / "run.json").write_text(json.dumps(record, indent=2) + "\n")
            try:
                with (output / "console.log").open("w") as log:
                    with redirect_stdout(ConsoleLog(sys.stdout, log)), redirect_stderr(ConsoleLog(sys.stderr, log)):
                        try:
                            click.echo(f"Run artifacts: {output}")
                            with run_runtime():
                                snapshot_inputs(module_root, output)
                                result = callback(*args, **kwargs)
                            write_trace(output)
                        except BaseException as error:
                            record["status"] = "interrupted" if isinstance(error, KeyboardInterrupt) else "failed"
                            record["error"] = {"type": type(error).__name__, "message": str(error)}
                            (output / "error.log").write_text(traceback.format_exc())
                            log.write(f"\n{record['status'].upper()}: {error}\nArtifacts: {output}\n")
                            raise
                        else:
                            record["status"] = "completed"
                            return result
            finally:
                try:
                    record["finished_at"] = datetime.now(timezone.utc).isoformat()
                    (output / "run.json").write_text(json.dumps(record, indent=2) + "\n")
                    write_index(output, record)
                finally:
                    _output.reset(token)
                    for name, value in previous.items():
                        if value is None:
                            os.environ.pop(name, None)
                        else:
                            os.environ[name] = value

        return run

    return decorate
